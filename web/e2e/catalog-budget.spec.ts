test('reader_can_view_catalog_without_mutation', async ({ browser, page }) => {
  test.setTimeout(120_000);
  await page.setViewportSize({ width: 390, height: 844 });
  await signIn(page);
  const household = await createHousehold(page, 'reader');
  await openSection(page, 'Categorías y comercios');
  const createCategory = waitForApi(page, 'POST', '/api/finance/catalog/categories');
  await page.locator('form.catalog-create [name="newName"]').fill('QA Solo lectura');
  await page.locator('form.catalog-create').getByRole('button', { name: 'Agregar' }).click();
  expect((await createCategory).status()).toBe(201);
  await openSpaces(page);
  await page.locator('[name="inviteEmail"]').fill('reader@example.test');
  await page.locator('[name="inviteRole"]').selectOption('Reader');
  const invite = waitForApi(page, 'POST', `/api/workspaces/${household.id}/invitations`);
  await page.getByRole('button', { name: 'Crear invitación' }).click();
  const invitation = await invite;
  expect(invitation.status()).toBe(200);
  const shareUrl = (await invitation.json() as { shareUrl: string }).shareUrl;
  const readerContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const reader = await readerContext.newPage();
  await reader.goto(new URL(shareUrl, page.url()).toString());
  await reader.getByLabel('Usuario local de prueba').selectOption('reader');
  const login = waitForApi(reader, 'POST', '/api/auth/development');
  await reader.getByRole('button', { name: 'Ingresar como usuario de prueba' }).click();
  expect((await login).status()).toBe(204);
  const accept = waitForApi(reader, 'POST', '/api/invitations/accept');
  await reader.getByRole('button', { name: 'Aceptar invitación' }).click();
  expect((await accept).status()).toBe(200);
  await expect(reader.locator('.workspace-picker select')).toHaveValue(household.id);
  await openSection(reader, 'Categorías y comercios');
  await expect(reader.getByText('QA Solo lectura', { exact: true })).toBeVisible();
  await expect(reader.getByText('No tenés acceso de lectura a este espacio.')).toHaveCount(0);
  await expect(reader.locator('form.catalog-create')).toHaveCount(0);
  const permission = await reader.evaluate(async id => {
    const response = await fetch('/api/finance/catalog', { headers: { 'X-Workspace-Id': id } });
    return { status: response.status, catalog: await response.json() };
  }, household.id);
  expect(permission.status).toBe(200);
  expect(permission.catalog.categories.some((item: any) => item.name === 'QA Solo lectura')).toBe(true);
  const csrf = await reader.evaluate(async () => (await (await fetch('/api/auth/session')).json()).csrfToken as string);
  const denied = await reader.request.post('/api/finance/catalog/categories', {
    data: { id: randomUUID(), name: 'QA No autorizado', kind: 'Expense' },
    headers: { 'X-CSRF-TOKEN': csrf, 'X-Workspace-Id': household.id },
  });
  expect(denied.status()).toBe(403);
  const after = await reader.evaluate(async id => {
    const response = await fetch('/api/finance/catalog', { headers: { 'X-Workspace-Id': id } });
    return response.json();
  }, household.id);
  expect(after.categories.some((item: any) => item.name === 'QA No autorizado')).toBe(false);
  await screenshotOne(reader, 'reader-catalog-390x844.png');
  await reader.setViewportSize({ width: 360, height: 800 });
  await screenshotOne(reader, 'reader-catalog-360x800.png');
  await reader.setViewportSize({ width: 1280, height: 800 });
  await screenshotOne(reader, 'reader-catalog-1280x800.png');
  await readerContext.close();
});

